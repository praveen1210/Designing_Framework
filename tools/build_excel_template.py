"""
Embed the Excel workbook into web/excel_template.js for the "Export Excel" button.

Run again whenever "PROP_Calculator(Square) .xlsx" changes (new formulas, layout, logos):

    python tools/build_excel_template.py "../PROP_Calculator(Square) .xlsx"

The page fills a copy of this workbook with the values from the page; the
original file is never changed.
"""
import base64
import sys
import zipfile
from pathlib import Path

src = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[2] / "PROP_Calculator(Square) .xlsx")
out = Path(__file__).resolve().parents[1] / "web" / "excel_template.js"

with zipfile.ZipFile(src) as z:  # fails early if the file is not a real .xlsx
    names = z.namelist()
    assert "xl/workbook.xml" in names, "not an Excel workbook"

data = base64.b64encode(src.read_bytes()).decode()
out.write_text(
    f"// Generated by tools/build_excel_template.py from {src.name}\n"
    "// Base64 of the workbook used by Export Excel (filled in the browser, original untouched).\n"
    f'window.EXCEL_TEMPLATE = {{ name: {src.name!r}, data: "{data}" }};\n',
    encoding="utf8",
)
print(f"written {out} ({len(data) // 1024} KB)")
